#!/usr/bin/env node
// Regenerates src/core/starter-templates.ts from starter-templates/*.md.
// Wired into pnpm build / pnpm dev via the prebuild / predev hooks in
// package.json so the inlined TS module never drifts from the on-disk
// source-of-truth markdown.

import fs from "node:fs/promises";
import path from "node:path";
import url from "node:url";

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const SOURCE_DIR = path.join(ROOT, "starter-templates");
const TARGET = path.join(ROOT, "src", "core", "starter-templates.ts");

const HEADER = `// Auto-generated from starter-templates/*.md by scripts/generate-starter-templates.mjs.
// Do not edit this file by hand — edit the markdown source and re-run
// \`pnpm build\` (or \`pnpm dev\`) to regenerate.

export interface StarterTemplate {
  filename: string;
  content: string;
}

export const STARTER_TEMPLATES: StarterTemplate[] = [
`;

const FOOTER = `];
`;

const files = (await fs.readdir(SOURCE_DIR))
  .filter((f) => f.endsWith(".md"))
  .sort();

if (files.length === 0) {
  console.error(`No markdown files found in ${SOURCE_DIR}`);
  process.exit(1);
}

const entries = await Promise.all(
  files.map(async (f) => ({
    filename: f,
    content: await fs.readFile(path.join(SOURCE_DIR, f), "utf8"),
  }))
);

const body = entries
  .map(
    (e) =>
      `  {\n    filename: ${JSON.stringify(e.filename)},\n    content: ${JSON.stringify(e.content)},\n  },`
  )
  .join("\n");

await fs.writeFile(TARGET, HEADER + body + "\n" + FOOTER);
console.log(`Generated ${path.relative(ROOT, TARGET)} from ${entries.length} starter templates.`);
